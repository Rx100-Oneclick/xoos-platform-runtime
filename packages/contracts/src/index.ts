export type XOOSDeliveryType = "native_esm" | "isolated_iframe" | "legacy_iframe";

export interface XOOSRuntimeContext {
  user: { id: string };
  tenant: { id: string | null };
  client: { id: string };
  runtime: { minimumVersion: string };
  scopes: string[];
}

export interface XOOSFeedMicroapp {
  microappKey: string;
  displayName: string;
  elementName: string | null;
  deliveryType: XOOSDeliveryType;
  version: string;
  /** Trusted deployment digest in sha256:<64-hex> format. */
  integrity: string;
  contractVersion: string | null;
  minimumRuntimeVersion: string | null;
}

export interface XOOSMicroappArtifactAccess {
  microappKey: string;
  version: string;
  /** Short-lived URL generated by xoos-runtime for the private manifest object. */
  manifestUrl: string;
  /** Short-lived URL generated by xoos-runtime for the exact private ESM artifact. */
  entryUrl: string;
  /** Trusted deployment digest in sha256:<64-hex> format. */
  integrity: string;
  /** Signed artifact URL lifetime in seconds. */
  expiresIn: number;
}

export interface XOOSRuntimeFeed {
  schemaVersion: "1";
  clientId: string;
  runtimeVersion: string;
  generatedAt: string;
  microapps: XOOSFeedMicroapp[];
}

export interface XOOSMicroappManifest {
  schemaVersion: "1";
  microappKey: string;
  version: string;
  elementName: string;
  /** Release metadata only. Runtime does not use this field as the network URL. */
  entry: string;
  /** Optional during migration; new manifests should emit native_esm explicitly. */
  deliveryType?: "native_esm";
  /**
   * Optional consistency metadata during migration. The authoritative digest is
   * XOOSFeedMicroapp.integrity, which is sourced from the deployment registry.
   */
  integrity?: {
    algorithm: "sha256";
    value: string;
  };
  contractVersion: string;
  minimumRuntimeVersion: string;
}

export interface XOOSCapabilityRequest<T = unknown> {
  input: T;
  microappKey?: string;
}

export interface XOOSCapabilityResponse<T = unknown> {
  ok: boolean;
  data?: T;
  error?: { code: string; message: string };
  traceId: string;
}

export interface XOOSTelemetryEvent {
  event: string;
  microappKey?: string;
  traceId?: string;
  occurredAt: string;
  attributes?: Record<string, string | number | boolean | null>;
}

export interface XOOSDataSourceConfig {
  projectKey: string;
  provider: "supabase";
  supabaseUrl: string;
  publishableKey: string;
}

export interface XOOSDataAccessSession {
  accessToken: string;
  expiresAt: number;
  dataSource: XOOSDataSourceConfig;
}

export interface XOOSDataBridge {
  getAccessToken: (projectKey: string) => Promise<string>;
  getProjectConfig: (projectKey: string) => Promise<XOOSDataSourceConfig>;
}

export interface XOOSNavigationOptions {
  target?: HTMLElement;
  props?: Record<string, unknown>;
}

export interface XOOSMicroappBridge {
  context: XOOSRuntimeContext;
  navigation: {
    navigate: (
      microappKey: string,
      targetOrOptions?: HTMLElement | XOOSNavigationOptions
    ) => Promise<void>;
  };
  events: {
    emit: (event: string, payload?: unknown) => void;
    on: (event: string, handler: (payload: unknown) => void) => () => void;
  };
  services: {
    request: <T>(capability: string, input?: unknown, microappKey?: string) => Promise<T>;
  };
  data: XOOSDataBridge;
  telemetry: {
    track: (
      event: string,
      attributes?: Record<string, string | number | boolean | null>,
      microappKey?: string
    ) => Promise<void>;
  };
}

export interface XOOSMicroappElement extends HTMLElement {
  xoos?: XOOSMicroappBridge;
  xoosProps?: Record<string, unknown>;
}
